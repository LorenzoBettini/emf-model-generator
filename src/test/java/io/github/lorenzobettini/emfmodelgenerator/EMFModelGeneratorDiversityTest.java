package io.github.lorenzobettini.emfmodelgenerator;

import static io.github.lorenzobettini.emfmodelgenerator.EMFTestUtils.assertEAttributeExists;
import static io.github.lorenzobettini.emfmodelgenerator.EMFTestUtils.assertEClassExists;
import static io.github.lorenzobettini.emfmodelgenerator.EMFTestUtils.assertEReferenceExists;
import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Random;
import java.util.Set;
import java.util.TreeSet;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.Function;

import org.eclipse.emf.common.util.Diagnostic;
import org.eclipse.emf.ecore.EClass;
import org.eclipse.emf.ecore.EPackage;
import org.eclipse.emf.ecore.util.EcoreUtil;
import org.junit.jupiter.api.Test;

import net.datafaker.Faker;

/**
 * BibTeX reproducibility and diversity experiment (20 primary models per strategy).
 * A/B use 12 entries and 12 fields per entry with ordinary round-robin selection.
 * C uses uniform, independent draws with replacement from the concrete subtype lists
 * sorted by namespace URI/class name. A separate Random(seed) draws entries in [6,18]
 * and fields per entry in [4,16]; the latter count is shared by entries in that run.
 * Subtype selection uses Random(seed XOR 0x5EED), and Datafaker uses Random(seed),
 * Locale.ENGLISH, with no time-dependent providers. Every run reloads the metamodel.
 * Reports are regenerated by {@code ./mvnw -Dtest=EMFModelGeneratorDiversityTest test}.
 *
 * <p>EMF structural validity does not establish semantic BibTeX validity or suitability
 * for every MDE tool. Seeded sampling does not guarantee systematic subtype coverage.
 * Identical signatures describe in-memory reproducibility, without requiring XMI equality.
 *
 * @author Lorenzo Bettini
 */
class EMFModelGeneratorDiversityTest {

	static final String METAMODEL = "target/external-metamodels/BibTeX.ecore";

	/**
	 * The three independently configured strategies.
	 *
	 * @author Lorenzo Bettini
	 */
	enum Strategy {
		A, B, C
	}

	/**
	 * One primary run; replay models are checks, not additional sample members.
	 *
	 * @author Lorenzo Bettini
	 */
	record Measurement(Strategy strategy, int run, int seed, int entries, int fieldsPerEntry,
			ModelDiversityMetrics.Snapshot snapshot, Set<String> entryTypes,
			Set<String> fieldTypes, String firstEntryType, String firstFieldType,
			boolean valid, List<String> diagnostics) {
	}

	/**
	 * A primary measurement and whether its independently generated replay agrees.
	 *
	 * @author Lorenzo Bettini
	 */
	record Run(Measurement measurement, boolean reproduced, List<String> replayDiagnostics) {
	}

	@Test
	void reproducibilityAndDiversity() throws IOException {
		var registryBefore = new HashMap<>(EPackage.Registry.INSTANCE);
		var runs = new ArrayList<Run>();
		for (var strategy : Strategy.values()) {
			Measurement baseline = null;
			for (int run = 1; run <= 20; run++) {
				var seed = strategy == Strategy.A ? 0 : run;
				var primary = generate(strategy, run, seed, false);
				if (baseline == null) {
					baseline = primary;
				}
				var replay = strategy == Strategy.A ? baseline
						: generate(strategy, run, seed, false);
				var reproduced = primary.snapshot().equals(replay.snapshot())
						&& primary.valid() && replay.valid();
				runs.add(new Run(primary, reproduced, replay.diagnostics()));
			}
		}
		// Write every measurement before asserting, retaining failed validation diagnostics.
		BibtexDiversityReport.write(runs);
		assertThat(EPackage.Registry.INSTANCE).containsExactlyInAnyOrderEntriesOf(registryBefore);
		assertThat(runs).allSatisfy(run -> {
			assertThat(run.measurement().valid()).as("%s", run.measurement()).isTrue();
			assertThat(run.reproduced()).as("Replay: %s", run).isTrue();
		});
		var a = measurements(runs, Strategy.A);
		var b = measurements(runs, Strategy.B);
		var c = measurements(runs, Strategy.C);
		assertThat(distinct(a, ModelDiversityMetrics.Snapshot::values)).isEqualTo(1);
		assertThat(distinct(a, ModelDiversityMetrics.Snapshot::types)).isEqualTo(1);
		assertThat(distinct(a, ModelDiversityMetrics.Snapshot::topology)).isEqualTo(1);
		assertThat(a).allSatisfy(m -> {
			assertThat(m.entries()).isEqualTo(12);
			assertThat(m.fieldsPerEntry()).isEqualTo(12);
			assertThat(m.snapshot().objectCount()).isEqualTo(157);
			assertThat(m.entryTypes()).hasSize(12);
			assertThat(m.fieldTypes()).hasSize(29);
		});
		assertThat(distinct(b, ModelDiversityMetrics.Snapshot::values)).isGreaterThan(1);
		assertThat(b).allSatisfy(m -> {
			assertThat(m.snapshot().types()).isEqualTo(a.getFirst().snapshot().types());
			assertThat(m.snapshot().topology()).isEqualTo(a.getFirst().snapshot().topology());
			assertThat(m.snapshot().values()).isNotEqualTo(a.getFirst().snapshot().values());
		});
		assertThat(distinct(c, ModelDiversityMetrics.Snapshot::values)).isGreaterThan(1);
		assertThat(distinct(c, ModelDiversityMetrics.Snapshot::types)).isGreaterThan(1);
		assertThat(distinct(c, ModelDiversityMetrics.Snapshot::topology)).isGreaterThan(1);
		// Fixed positions isolate subtype changes from changes in population size.
		assertThat(c.stream().map(Measurement::firstEntryType).distinct().count()).isGreaterThan(1);
		assertThat(c.stream().map(Measurement::firstFieldType).distinct().count()).isGreaterThan(1);
		assertThat(c).allSatisfy(m -> {
			assertThat(m.entries()).isBetween(6, 18);
			assertThat(m.fieldsPerEntry()).isBetween(4, 16);
			assertThat(m.snapshot().objectCount())
					.isEqualTo(1 + m.entries() * (1 + m.fieldsPerEntry()));
		});
		// No assertion that every seed is unique or every random model covers all types.
	}

	@Test
	void valueProviderConsumptionDoesNotChangeStructuralDecisions() throws IOException {
		var ordinary = generate(Strategy.C, 1, 7, false);
		var extraValueDraw = generate(Strategy.C, 1, 7, true);
		assertThat(ordinary.valid()).isTrue();
		assertThat(extraValueDraw.valid()).isTrue();
		assertThat(extraValueDraw.snapshot().values()).isNotEqualTo(ordinary.snapshot().values());
		assertThat(extraValueDraw.snapshot().types()).isEqualTo(ordinary.snapshot().types());
		assertThat(extraValueDraw.snapshot().topology()).isEqualTo(ordinary.snapshot().topology());
	}

	private Measurement generate(final Strategy strategy, final int run, final int seed,
			final boolean extraValueDraw) throws IOException {
		var generator = new EMFModelGenerator();
		try {
			var packages = generator.loadEcoreModelPackages(METAMODEL);
			var bibtex = packages.stream().filter(p -> "BIBTEX".equals(p.getName()))
					.findFirst().orElseThrow();
			var rootClass = assertEClassExists(bibtex, "Bibtex");
			var entryClass = assertEClassExists(bibtex, "Entry");
			var fieldClass = assertEClassExists(bibtex, "Field");
			var entriesReference = assertEReferenceExists(rootClass, "entries");
			var fieldsReference = assertEReferenceExists(entryClass, "fields");
			var entryCandidates = candidates(entryClass);
			var fieldCandidates = candidates(fieldClass);
			assertThat(entryCandidates).hasSize(12);
			assertThat(fieldCandidates).hasSize(29);
			var populator = generator.getInstancePopulator();
			int entries = 12;
			int fields = 12;
			if (strategy == Strategy.C) {
				var sizes = new Random(seed);
				entries = sizes.nextInt(6, 19);
				fields = sizes.nextInt(4, 17);
				var selection = new Random(seed ^ 0x5EEDL);
				populator.functionForContainmentReference(entriesReference,
						owner -> EcoreUtil.create(entryCandidates.get(
								selection.nextInt(entryCandidates.size()))));
				populator.functionForContainmentReference(fieldsReference,
						owner -> EcoreUtil.create(fieldCandidates.get(
								selection.nextInt(fieldCandidates.size()))));
			}
			populator.setContainmentReferenceMaxCountFor(entriesReference, entries);
			populator.setContainmentReferenceMaxCountFor(fieldsReference, fields);
			populator.setMaxDepth(2);
			if (strategy != Strategy.A) {
				var faker = new Faker(Locale.ENGLISH, new Random(seed));
				if (extraValueDraw) {
					faker.lorem().sentence(4);
				}
				var keyIndex = new AtomicInteger();
				populator.functionForAttribute(assertEAttributeExists(entryClass, "key"),
						owner -> faker.name().lastName().replaceAll("[^A-Za-z0-9]", "")
								+ "_" + keyIndex.incrementAndGet());
				// Generic text demonstrates customization, not field-specific BibTeX semantics.
				populator.functionForAttribute(assertEAttributeExists(fieldClass, "value"),
						owner -> faker.lorem().sentence(4));
			}
			var root = generator.generateFrom(rootClass);
			var firstEntry = EMFUtils.getAsEObjectsList(root, entriesReference).getFirst();
			var firstField = EMFUtils.getAsEObjectsList(firstEntry, fieldsReference).getFirst();
			var snapshot = ModelDiversityMetrics.measure(List.of(root));
			var validation = generator.validate();
			return new Measurement(strategy, run, seed, entries, fields, snapshot,
					covered(snapshot, entryCandidates), covered(snapshot, fieldCandidates),
					ModelDiversityMetrics.classifierId(firstEntry.eClass()),
					ModelDiversityMetrics.classifierId(firstField.eClass()),
					validation.isValid(), validation.rejectedDiagnostics().stream()
							.map(Diagnostic::getMessage).toList());
		} finally {
			// Remove only registrations owned by this fresh generator, including PrimitiveTypes.
			generator.unloadEcoreModels();
			generator.getResourceSet().getResources().forEach(r -> r.unload());
			generator.getResourceSet().getResources().clear();
		}
	}

	private static List<EClass> candidates(final EClass base) {
		return EMFUtils.findAllInstantiableSubclasses(base).stream()
				.sorted(Comparator.comparing(ModelDiversityMetrics::classifierId)).toList();
	}

	private static Set<String> covered(final ModelDiversityMetrics.Snapshot snapshot,
			final List<EClass> candidates) {
		var covered = new TreeSet<String>();
		candidates.stream().map(ModelDiversityMetrics::classifierId)
				.filter(snapshot.typeCounts()::containsKey).forEach(covered::add);
		return Set.copyOf(covered);
	}

	static List<Measurement> measurements(final List<Run> runs, final Strategy strategy) {
		return runs.stream().map(Run::measurement).filter(m -> m.strategy() == strategy).toList();
	}

	static long distinct(final List<Measurement> sample,
			final Function<ModelDiversityMetrics.Snapshot, String> signature) {
		return sample.stream().map(Measurement::snapshot).map(signature).distinct().count();
	}
}
